import fs from "node:fs/promises";
import path from "node:path";

const rootDirectory = process.cwd();
const galleryDirectory = path.join(rootDirectory, "public/assets/gallery");
const outputDirectory = path.join(rootDirectory, "lib/generated");
const outputFile = path.join(outputDirectory, "gallery-images.ts");
const supportedImageExtensions = new Set([
  ".avif",
  ".gif",
  ".jpeg",
  ".jpg",
  ".png",
  ".webp",
]);

async function getGalleryImages() {
  try {
    const entries = await fs.readdir(galleryDirectory, { withFileTypes: true });

    return entries
      .filter((entry) => {
        const extension = path.extname(entry.name).toLowerCase();
        return entry.isFile() && supportedImageExtensions.has(extension);
      })
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((entry, index) => ({
        alt: `Ākēdo Festival gallery photo ${index + 1}`,
        src: `/assets/gallery/${encodeURIComponent(entry.name)}`,
      }));
  } catch (error) {
    if (error.code === "ENOENT") {
      return [];
    }

    throw error;
  }
}

const galleryImages = await getGalleryImages();
const fileContents = `/**
 * This file is generated by scripts/generate-gallery-manifest.mjs.
 * Drop images into public/assets/gallery and run the build/dev command again.
 */

export const galleryImages = ${JSON.stringify(galleryImages, null, 2)} as const;
`;

await fs.mkdir(outputDirectory, { recursive: true });
await fs.writeFile(outputFile, fileContents);

console.log(`Generated ${galleryImages.length} gallery image entries.`);
